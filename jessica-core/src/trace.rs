//! Versioned trace envelope for lossless persistence and audit.
//!
//! The runtime and harness continue to broadcast [`AgentEvent`]s. A
//! [`TraceEvent`] wraps one observed event, or a trace-level marker, together
//! with the turn and attempt context needed to prove that a turn's record is
//! complete.
//!
//! A turn trace starts with [`TracePayload::TurnStarted`], contains zero or
//! more agent/gap payloads, and ends with [`TracePayload::TurnEnded`]. A trace
//! without a terminal marker is intentionally readable and explicitly
//! incomplete; it is never silently treated as complete.
//!
//! Schema version 2 adds no envelope field and no new [`TracePayload`] variant:
//! it marks the expanded [`AgentEvent`] vocabulary (session input, rounds,
//! usage, permissions, and child-session lifecycle). Version-1 traces remain
//! readable, but a version-1 trace must not contain a version-2-only event.
//! Readers reject versions newer than [`TRACE_SCHEMA_VERSION`].

use serde::{Deserialize, Serialize};

use crate::types::{AgentEvent, Message, SessionEndReason, SessionId};

/// Version of the trace envelope produced by this build.
///
/// A reader must reject envelopes whose version it does not understand rather
/// than guessing at their semantics. See
/// [`MIN_SUPPORTED_TRACE_SCHEMA_VERSION`] for the oldest readable version.
pub const TRACE_SCHEMA_VERSION: u16 = 2;

/// Oldest trace schema version this build can read.
///
/// Version-1 traces predate the explicit round, usage, permission, and
/// child-session events. Their smaller event vocabulary is still valid; absent
/// facts are not synthesized during decoding.
pub const MIN_SUPPORTED_TRACE_SCHEMA_VERSION: u16 = 1;

/// Returns whether `version` is readable by this build.
pub fn is_supported_trace_schema_version(version: u16) -> bool {
    (MIN_SUPPORTED_TRACE_SCHEMA_VERSION..=TRACE_SCHEMA_VERSION).contains(&version)
}

/// Opaque identifier for one user-visible turn.
///
/// Every acceptance attempt of one turn shares the same [`TurnId`], while each
/// attempt keeps its own [`SessionId`]. The identifier is generated by the
/// host; the runtime never reads it and it never influences agent behaviour.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(transparent)]
pub struct TurnId(String);

impl TurnId {
    /// Creates a turn identifier from any string-like value.
    ///
    /// The store rejects an empty identifier when the trace is appended.
    pub fn new(id: impl Into<String>) -> Self {
        Self(id.into())
    }

    /// Returns the identifier as a string slice.
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl std::fmt::Display for TurnId {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.write_str(&self.0)
    }
}

impl From<String> for TurnId {
    fn from(id: String) -> Self {
        Self(id)
    }
}

impl From<&str> for TurnId {
    fn from(id: &str) -> Self {
        Self(id.to_owned())
    }
}

/// One versioned entry in a turn trace.
///
/// Storage assigns the per-turn sequence number and wall-clock timestamp; they
/// are deliberately not part of the envelope so the exact payload cannot
/// disagree with the row that stores it.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct TraceEvent {
    /// Envelope schema version; see [`TRACE_SCHEMA_VERSION`].
    pub schema_version: u16,
    /// Turn this entry belongs to.
    pub turn_id: TurnId,
    /// One-based acceptance attempt, when the entry belongs to one.
    pub attempt: Option<u32>,
    /// Session attributed to the entry, when one exists.
    ///
    /// Agent events emitted between attempts, such as an acceptance failure,
    /// point at the attempt whose output was judged. Turn-level markers leave
    /// this unset.
    pub session_id: Option<SessionId>,
    /// Entry payload.
    pub payload: TracePayload,
}

impl TraceEvent {
    /// Creates an envelope stamped with [`TRACE_SCHEMA_VERSION`].
    pub fn new(
        turn_id: TurnId,
        attempt: Option<u32>,
        session_id: Option<SessionId>,
        payload: TracePayload,
    ) -> Self {
        Self {
            schema_version: TRACE_SCHEMA_VERSION,
            turn_id,
            attempt,
            session_id,
            payload,
        }
    }
}

/// Payload carried by one [`TraceEvent`].
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum TracePayload {
    /// An event broadcast by the runtime, harness, or CLI governance.
    Agent {
        /// The observed event.
        event: AgentEvent,
    },
    /// The recorder observed a broadcast gap and could not persist the lost
    /// events.
    Gap {
        /// Number of events reported lost by the broadcast receiver.
        skipped: u64,
        /// Why the events were lost.
        reason: TraceGapReason,
    },
    /// The turn started.
    TurnStarted {
        /// Whether the turn started fresh or from a recovered checkpoint.
        mode: TraceTurnMode,
        /// Initial conversation supplied to the turn's first attempt.
        ///
        /// This makes the trace self-contained: a reader does not need the
        /// legacy `sessions` metadata table to know what the model received.
        messages: Vec<Message>,
    },
    /// The turn ended normally.
    ///
    /// A trace whose store write failed, or whose recorder observed a gap,
    /// never receives this marker. Its absence is the completeness signal.
    TurnEnded {
        /// Final governed reason for the turn.
        reason: SessionEndReason,
    },
}

impl TracePayload {
    /// Returns the stable storage tag for this payload.
    pub fn kind(&self) -> &'static str {
        match self {
            Self::Agent { .. } => "agent",
            Self::Gap { .. } => "gap",
            Self::TurnStarted { .. } => "turn_started",
            Self::TurnEnded { .. } => "turn_ended",
        }
    }

    /// Returns the minimum trace schema version that can carry this payload.
    ///
    /// Only agent payloads can require version 2; the trace envelope itself is
    /// unchanged from version 1.
    pub fn required_trace_schema_version(&self) -> u16 {
        match self {
            Self::Agent { event } => event.required_trace_schema_version(),
            Self::Gap { .. } | Self::TurnStarted { .. } | Self::TurnEnded { .. } => 1,
        }
    }
}

/// How a turn obtained its initial conversation.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum TraceTurnMode {
    /// The caller supplied a new conversation.
    Fresh,
    /// The conversation came from a recovered session checkpoint.
    Resumed,
}

/// Why a trace contains a gap.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum TraceGapReason {
    /// The broadcast receiver lagged and reported dropped events.
    BroadcastLagged,
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::types::{SessionEndReason, SessionId};
    use serde_json::json;

    fn turn() -> TurnId {
        TurnId::new("turn-1")
    }

    #[test]
    fn a_new_envelope_is_stamped_with_the_supported_schema_version() {
        let event = TraceEvent::new(
            turn(),
            Some(1),
            Some(SessionId::new("cli-1")),
            TracePayload::TurnEnded {
                reason: SessionEndReason::Completed,
            },
        );

        assert_eq!(event.schema_version, TRACE_SCHEMA_VERSION);
        assert_eq!(event.schema_version, 2);
        assert!(is_supported_trace_schema_version(1));
        assert!(is_supported_trace_schema_version(2));
        assert!(!is_supported_trace_schema_version(0));
        assert!(!is_supported_trace_schema_version(3));
    }

    #[test]
    fn every_payload_kind_round_trips_without_losing_context() {
        let session = SessionId::new("cli-7");
        let cases = [
            TraceEvent::new(
                turn(),
                Some(1),
                Some(session.clone()),
                TracePayload::Agent {
                    event: AgentEvent::ModelDelta {
                        text: "hello".to_owned(),
                    },
                },
            ),
            TraceEvent::new(
                turn(),
                Some(2),
                Some(session.clone()),
                TracePayload::Gap {
                    skipped: 17,
                    reason: TraceGapReason::BroadcastLagged,
                },
            ),
            TraceEvent::new(
                turn(),
                None,
                Some(session.clone()),
                TracePayload::TurnStarted {
                    mode: TraceTurnMode::Fresh,
                    messages: vec![Message::system("system"), Message::user("fix it")],
                },
            ),
            TraceEvent::new(
                turn(),
                None,
                None,
                TracePayload::TurnEnded {
                    reason: SessionEndReason::AcceptanceFailed,
                },
            ),
        ];

        for event in cases {
            let json = serde_json::to_value(&event).expect("trace event must serialize");
            let decoded: TraceEvent =
                serde_json::from_value(json.clone()).expect("trace event must deserialize");
            assert_eq!(decoded, event);
            assert_eq!(decoded.payload.kind(), event.payload.kind());
        }
    }

    #[test]
    fn the_json_shape_names_the_kind_and_nests_the_agent_event() {
        let event = TraceEvent::new(
            TurnId::new("turn-9"),
            Some(1),
            Some(SessionId::new("cli-9")),
            TracePayload::Agent {
                event: AgentEvent::ToolCallFinished {
                    result: crate::types::ToolResult::success("call-1", "ok"),
                },
            },
        );

        let json = serde_json::to_value(&event).expect("trace event must serialize");
        assert_eq!(json["schema_version"], json!(2));
        assert_eq!(json["turn_id"], json!("turn-9"));
        assert_eq!(json["attempt"], json!(1));
        assert_eq!(json["session_id"], json!("cli-9"));
        assert_eq!(json["payload"]["kind"], json!("agent"));
        assert_eq!(
            json["payload"]["event"]["type"],
            json!("tool_call_finished")
        );
    }

    #[test]
    fn payload_versions_follow_the_agent_event_vocabulary() {
        let v1_payloads = [
            TracePayload::Gap {
                skipped: 1,
                reason: TraceGapReason::BroadcastLagged,
            },
            TracePayload::TurnStarted {
                mode: TraceTurnMode::Fresh,
                messages: vec![Message::user("hi")],
            },
            TracePayload::TurnEnded {
                reason: SessionEndReason::Completed,
            },
            TracePayload::Agent {
                event: AgentEvent::ModelDelta {
                    text: "hello".to_owned(),
                },
            },
            TracePayload::Agent {
                event: AgentEvent::SessionStarted {
                    session_id: SessionId::new("cli-1"),
                    messages: Vec::new(),
                },
            },
        ];
        for payload in v1_payloads {
            assert_eq!(payload.required_trace_schema_version(), 1);
        }

        let v2_payloads = [
            TracePayload::Agent {
                event: AgentEvent::SessionStarted {
                    session_id: SessionId::new("cli-2"),
                    messages: vec![Message::user("hello")],
                },
            },
            TracePayload::Agent {
                event: AgentEvent::RoundStarted { round: 1 },
            },
            TracePayload::Agent {
                event: AgentEvent::RoundFinished {
                    round: 1,
                    usage: None,
                },
            },
        ];
        for payload in v2_payloads {
            assert_eq!(payload.required_trace_schema_version(), 2);
        }
    }

    #[test]
    fn turn_ids_are_transparent_strings_with_display_and_conversions() {
        let from_str: TurnId = "turn-a".into();
        let from_string: TurnId = String::from("turn-b").into();

        assert_eq!(from_str.as_str(), "turn-a");
        assert_eq!(from_str.to_string(), "turn-a");
        assert_eq!(from_string.as_str(), "turn-b");
        assert_eq!(
            serde_json::to_value(&from_str).expect("turn id must serialize"),
            json!("turn-a")
        );
    }
}
